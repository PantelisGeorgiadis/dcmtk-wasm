#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * Renders the JSON output of bench.js (--json <path>) as a Markdown comment
 * body, suitable for posting on a pull request. Results are grouped per
 * workload, then per benchmark case, with the fastest library first.
 *
 * Usage:
 *   node benchmark/report.js <results.json>
 *
 * The Markdown is written to stdout.
 */

const fs = require('fs');

/**
 * Hidden marker used to find (and update) a previously posted comment.
 * @constant {string}
 */
const MARKER = '<!-- dcmtk-wasm-benchmark -->';

/**
 * Formats a duration in milliseconds, same style as bench.js tables.
 * @param {number} ms Duration in milliseconds.
 * @returns {string} The formatted duration.
 */
function fmt(ms) {
  return ms >= 1000 ? `${(ms / 1000).toFixed(3)} s` : `${ms.toFixed(2)} ms`;
}

function main() {
  const file = process.argv[2];
  if (!file) {
    console.error('Usage: node benchmark/report.js <results.json>');
    process.exit(1);
  }

  const data = JSON.parse(fs.readFileSync(file, 'utf8'));

  // Group results by workload, preserving the order produced by bench.js.
  const workloads = new Map();
  for (const r of data.results) {
    if (!workloads.has(r.workload)) {
      workloads.set(r.workload, []);
    }
    workloads.get(r.workload).push(r);
  }

  const lines = [];
  lines.push(MARKER);
  lines.push('## 📊 DICOM performance benchmark');
  lines.push('');
  lines.push(
    `Node ${data.node} · generated ${new Date(data.generatedAt)
      .toISOString()
      .replace('T', ' ')
      .slice(0, 16)} UTC`
  );

  for (const [workload, rows] of workloads) {
    lines.push('');
    lines.push(
      `### \`${workload}\` (${(rows[0].bytes / 1024).toFixed(0)} KiB, TS \`${
        rows[0].transferSyntax
      }\`)`
    );
    lines.push('');
    lines.push('| Case | Library | Mean | Median | P95 | Std dev | Rel. |');
    lines.push('| --- | --- | ---: | ---: | ---: | ---: | ---: |');

    // Group by case, fastest (lowest median) library first within each case.
    const cases = new Map();
    for (const r of rows) {
      if (!cases.has(r.case)) {
        cases.set(r.case, []);
      }
      cases.get(r.case).push(r);
    }
    for (const [caseName, caseRows] of cases) {
      caseRows.sort((a, b) => a.medianMs - b.medianMs);
      for (const r of caseRows) {
        lines.push(
          `| ${caseName} | ${r.library} | ${fmt(r.meanMs)} | ${fmt(r.medianMs)} | ` +
            `${fmt(r.p95Ms)} | ${r.stdMs.toFixed(2)} ms | ${r.relativeToBest.toFixed(2)}x |`
        );
      }
    }
  }

  lines.push('');
  lines.push('_Generated by `node benchmark/bench.js --json results.json`._');

  console.log(lines.join('\n'));
}

main();
